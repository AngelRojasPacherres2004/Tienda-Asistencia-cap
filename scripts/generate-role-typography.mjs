import { readFileSync, writeFileSync } from "node:fs";

// Keep the existing hierarchy and responsive rules while adding 3px to text.
function typography(source) {
  let output = "";
  const clean = source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/@import[^;]*;/g, "");
  let cursor = 0;
  while (cursor < clean.length) {
    const open = clean.indexOf("{", cursor);
    if (open < 0) break;
    let depth = 1, end = open + 1;
    while (end < clean.length && depth) { if (clean[end] === "{") depth++; if (clean[end] === "}") depth--; end++; }
    const selector = clean.slice(cursor, open).trim();
    const body = clean.slice(open + 1, end - 1);
    if (selector.startsWith("@media") && !selector.includes("print")) {
      const nested = typography(body);
      if (nested) output += `${selector} {\n${nested}}\n`;
    } else if (!selector.startsWith("@")) {
      const selectors = selector.split(",").map(s => s.trim()).filter(s => s.startsWith(".") && !/marketing|login|sidebar|brand|user-chip|logout-button/.test(s));
      const sizes = [...body.matchAll(/(?:^|;)\s*font-size\s*:\s*([^;]+)/g)];
      if (selectors.length && sizes.length) {
        const size = sizes.at(-1)[1].replace(/(\d+(?:\.\d+)?)px/g, (_, n) => `${Number(n) + 3}px`);
        output += `${selectors.map(s => `.app-theme ${s}`).join(", ")} { font-size: ${size}; }\n`;
      }
    }
    cursor = end;
  }
  return output;
}
