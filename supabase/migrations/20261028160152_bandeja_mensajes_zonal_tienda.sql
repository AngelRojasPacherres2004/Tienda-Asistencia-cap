CREATE TABLE IF NOT EXISTS public.bandeja_mensajes_zonal_tienda (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tienda_id INTEGER NOT NULL REFERENCES public.tiendas(id) ON DELETE CASCADE,
  remitente_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  destinatario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  mensaje TEXT NOT NULL CHECK (char_length(btrim(mensaje)) BETWEEN 1 AND 2000),
  leido_en TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT bandeja_mensajes_distintos_check CHECK (remitente_id <> destinatario_id)
);

CREATE INDEX IF NOT EXISTS bandeja_mensajes_tienda_fecha_idx
  ON public.bandeja_mensajes_zonal_tienda (tienda_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bandeja_mensajes_destinatario_fecha_idx
  ON public.bandeja_mensajes_zonal_tienda (destinatario_id, leido_en, created_at DESC);

ALTER TABLE public.bandeja_mensajes_zonal_tienda ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.bandeja_mensajes_zonal_tienda FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.bandeja_mensajes_zonal_tienda TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.bandeja_mensajes_zonal_tienda_id_seq TO service_role;

NOTIFY pgrst, 'reload schema';
COMMIT;
