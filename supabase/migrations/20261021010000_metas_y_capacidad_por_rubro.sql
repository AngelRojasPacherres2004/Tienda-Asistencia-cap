alter table public.tiendas
  add column if not exists capacidad_stock_calzado_unid integer,
  add column if not exists capacidad_stock_textil_unid integer;

alter table public.tiendas
  drop constraint if exists tiendas_capacidad_stock_calzado_unid_check,
  add constraint tiendas_capacidad_stock_calzado_unid_check
    check (capacidad_stock_calzado_unid is null or capacidad_stock_calzado_unid >= 0),
  drop constraint if exists tiendas_capacidad_stock_textil_unid_check,
  add constraint tiendas_capacidad_stock_textil_unid_check
    check (capacidad_stock_textil_unid is null or capacidad_stock_textil_unid >= 0);

create table if not exists public.metas_comerciales_tienda (
  id bigint generated by default as identity primary key,
  tienda_id bigint not null references public.tiendas(id) on delete cascade,
  anio smallint not null check (anio between 2024 and 2100),
  mes smallint not null check (mes between 1 and 12),
  meta_venta numeric(14,2) not null check (meta_venta >= 0),
  actualizado_por bigint references public.usuarios(id) on delete set null,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now(),
  unique (tienda_id, anio, mes)
);

create index if not exists metas_comerciales_tienda_periodo_idx
  on public.metas_comerciales_tienda (anio, mes, tienda_id);

alter table public.metas_comerciales_tienda enable row level security;
revoke all on table public.metas_comerciales_tienda from anon, authenticated;
revoke all on sequence public.metas_comerciales_tienda_id_seq from anon, authenticated;

comment on table public.metas_comerciales_tienda is
  'Metas mensuales editables por administrador de tienda y consumidas por el dashboard comercial general.';
comment on column public.tiendas.capacidad_stock_calzado_unid is
  'Capacidad máxima operativa de calzado, expresada en unidades.';
comment on column public.tiendas.capacidad_stock_textil_unid is
  'Capacidad máxima operativa de textil, expresada en unidades.';
