CREATE TABLE public.apoyos_administradores_tienda (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  tienda_id BIGINT NOT NULL REFERENCES public.tiendas(id) ON DELETE CASCADE,
  habilitado BOOLEAN NOT NULL DEFAULT true,
  creado_por BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
  actualizado_por BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (usuario_id, tienda_id)
);
CREATE INDEX apoyos_administradores_tienda_tienda_idx ON public.apoyos_administradores_tienda(tienda_id);
CREATE INDEX apoyos_administradores_tienda_creador_idx ON public.apoyos_administradores_tienda(creado_por);
CREATE INDEX apoyos_administradores_tienda_actualizador_idx ON public.apoyos_administradores_tienda(actualizado_por);
ALTER TABLE public.apoyos_administradores_tienda ENABLE ROW LEVEL SECURITY;
-- This app uses its own HttpOnly session and a server-only service role client.
REVOKE ALL ON public.apoyos_administradores_tienda FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.apoyos_administradores_tienda TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.apoyos_administradores_tienda_id_seq TO service_role;

NOTIFY pgrst, 'reload schema';
COMMIT;
