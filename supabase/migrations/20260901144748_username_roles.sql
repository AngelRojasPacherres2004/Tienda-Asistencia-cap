-- Los operadores ingresan con usuario y contraseña; la contraseña permanece
-- exclusivamente en Supabase Auth (hash seguro), nunca en una tabla pública.
create table if not exists public.dashboard_roles (
  id smallint generated by default as identity primary key,
  code text not null unique check (code ~ '^[a-z][a-z0-9_]{1,48}$'),
  name text not null,
  description text,
  sort_order smallint not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.dashboard_roles (code, name, description, sort_order)
values
  ('admin', 'Administrador', 'Administra accesos, publicaciones y mantenimiento.', 10),
  ('manager', 'Gestor', 'Consulta indicadores y opera funciones autorizadas.', 20),
  ('viewer', 'Consulta', 'Acceso de solo lectura al dashboard.', 30)
on conflict (code) do update set
  name = excluded.name,
  description = excluded.description,
  sort_order = excluded.sort_order;

alter table public.dashboard_users
  add column if not exists username_key text,
  add column if not exists role_id smallint references public.dashboard_roles(id);

update public.dashboard_users u
set username_key = lower(trim(u.usuario))
where username_key is null;

update public.dashboard_users u
set role_id = r.id
from public.dashboard_roles r
where u.role_id is null
  and r.code = coalesce(nullif(lower(trim(u.role)), ''), 'viewer');

update public.dashboard_users u
set role_id = r.id
from public.dashboard_roles r
where u.role_id is null and r.code = 'viewer';

alter table public.dashboard_users
  alter column username_key set not null,
  alter column role_id set not null;

create unique index if not exists dashboard_users_username_key_unique
  on public.dashboard_users (username_key);

create or replace function public.dashboard_normalize_username()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.usuario := trim(new.usuario);
  new.username_key := lower(new.usuario);
  if new.usuario !~ '^[A-Za-z0-9][A-Za-z0-9._-]{2,48}$' then
    raise exception 'El usuario debe tener entre 3 y 49 caracteres: letras, números, punto, guion o guion bajo.';
  end if;
  return new;
end;
$$;

drop trigger if exists dashboard_users_normalize_username on public.dashboard_users;
create trigger dashboard_users_normalize_username
before insert or update of usuario on public.dashboard_users
for each row execute function public.dashboard_normalize_username();

alter table public.dashboard_roles enable row level security;
revoke all on table public.dashboard_roles from anon;
revoke insert, update, delete on table public.dashboard_roles from authenticated;
grant select on table public.dashboard_roles to authenticated;

drop policy if exists "authenticated users can read role catalog" on public.dashboard_roles;
create policy "authenticated users can read role catalog"
on public.dashboard_roles for select
to authenticated
using (true);

comment on table public.dashboard_roles is
  'Catálogo escalable de roles. La gestión futura debe hacerse desde una interfaz administrativa autenticada.';
comment on column public.dashboard_users.username_key is
  'Clave normalizada para iniciar sesión sin correo.';
comment on column public.dashboard_users.role_id is
  'Rol del usuario dentro del catálogo dashboard_roles.';
