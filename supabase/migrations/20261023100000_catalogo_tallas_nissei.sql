create or replace view public.productos_con_talla
with (security_invoker = true)
as
with normalizados as (
  select
    p.*,
    translate(upper(coalesce(p.rubro, '')), 'ÁÉÍÓÚÑ', 'AEIOUN') as rubro_normalizado,
    translate(upper(concat_ws(' ', p.linea, p.descripcion)), 'ÁÉÍÓÚÑ', 'AEIOUN') as texto_genero
  from public.productos p
), clasificados as (
  select
    n.*,
    case
      when texto_genero like '%BEBE%' then 'BEBE'
      when texto_genero like '%JUVEN%' or texto_genero like '%JOVENCIT%' then 'JUVENIL'
      when texto_genero ~ '(^|[^A-Z])(KIDS|NINO|NINA|INFANTIL)([^A-Z]|$)' then 'KIDS'
      when texto_genero like '%DAMA%' or texto_genero like '%MUJER%' or texto_genero like '%FEMEN%' then 'DAMA'
      when texto_genero like '%CABALLERO%' or texto_genero like '%HOMBRE%' or texto_genero like '%MASCUL%' then 'CABALLERO'
      else 'ADULT'
    end as genero_talla
  from normalizados n
)
select
  c.*,
  t.id as talla_id,
  t.talla_display,
  t.talla_eur,
  t.talla_usa,
  t.segmento as segmento_talla,
  t.tipo_curva
from clasificados c
left join public.tallas_nissei t
  on t.rubro = c.rubro_normalizado
 and t.codigo_talla = c.codigo_talla
 and (
   t.genero = c.genero_talla
   or (t.rubro = 'TEXTIL' and t.genero = 'ADULT' and c.genero_talla in ('DAMA', 'CABALLERO', 'ADULT'))
   or (t.rubro = 'TEXTIL' and t.genero = 'KIDS' and c.genero_talla = 'BEBE')
 );

revoke all on table public.productos_con_talla from anon, authenticated;
grant select on table public.productos_con_talla to service_role;

comment on table public.tallas_nissei is
