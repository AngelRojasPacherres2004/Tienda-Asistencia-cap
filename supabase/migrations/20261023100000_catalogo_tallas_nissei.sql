-- Normaliza el sufijo de talla del codigo Nissei y publica un catalogo
-- reutilizable por inventario, ventas, ingresos y transferencias.

alter table public.productos
  add column if not exists codigo_base text generated always as (
    case
      when length(btrim(codigo_nissei)) = 14 then left(btrim(codigo_nissei), 11)
      else null
    end
  ) stored,
  add column if not exists codigo_talla varchar(3) generated always as (
    case
      when length(btrim(codigo_nissei)) = 14 then upper(right(btrim(codigo_nissei), 3))
      else null
    end
  ) stored;

create index if not exists productos_codigo_base_idx on public.productos (codigo_base);
create index if not exists productos_codigo_talla_idx on public.productos (codigo_talla);

comment on column public.productos.codigo_base is
  'Codigo Nissei sin los tres caracteres finales reservados para talla.';
comment on column public.productos.codigo_talla is
  'Tres caracteres finales del codigo Nissei. Admite catalogo historico y el formato canonico de 14 caracteres.';

create table if not exists public.tallas_nissei (
  id bigint generated by default as identity primary key,
  rubro text not null check (rubro in ('CALZADO', 'TEXTIL')),
  genero text not null,
  codigo_talla varchar(3) not null check (length(codigo_talla) = 3),
  talla_display text not null,
  talla_eur numeric(4,1),
  talla_usa numeric(4,1),
  segmento text not null,
  tipo_curva text,
  fuente text not null default 'TABLA TALLAS GENERAL CALZADO.xlsx',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (rubro, genero, codigo_talla)
);

