def validar_columnas_kpi(esquemas: dict[str, list[object]]) -> None:
    validar_nombres_medidas()
    errores: list[str] = []
    for tabla, requeridas in COLUMNAS_REQUERIDAS_KPI.items():
        columnas = esquemas.get(tabla)
        if columnas is None:
            errores.append(f"falta la tabla {tabla}")
            continue
        nombres = {getattr(c, "nombre", str(c)) for c in columnas}
        faltan = sorted(requeridas - nombres)
        if faltan:
            errores.append(f"{tabla} no contiene {faltan}")
    if errores:
        raise RuntimeError(
            "No se puede generar la tabla Medidas porque el modelo no cumple "
            "el contrato de KPI: " + "; ".join(errores)
        )


def validar_nombres_medidas() -> None:
    nombres = [medida.nombre for medida in MEDIDAS]
    repetidos = sorted({n for n in nombres if nombres.count(n) > 1})
    no_mayuscula = [n for n in nombres if n != n.upper()]
    if repetidos:
        raise RuntimeError(f"Hay medidas duplicadas: {repetidos}")
    if no_mayuscula:
        raise RuntimeError(f"Hay medidas que no están en mayúscula: {no_mayuscula}")


def cantidad_medidas() -> int:
    validar_nombres_medidas()
    return len(MEDIDAS)
